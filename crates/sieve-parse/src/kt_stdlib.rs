/// Whether the sorted list `list` holds `name`.
pub(crate) fn has(list: &[&str], name: &str) -> bool {
    list.binary_search(&name).is_ok()
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn every_list_is_sorted_and_free_of_duplicates() {
        for list in [
            TOP,
            TOP_BARE,
            EXT_ANY,
            EXT_ANY_PROPS,
            NO_RECV_BARE,
            NO_RECV_MEMBER,
            RECV_BARE,
            RECV_MEMBER,
        ] {
            assert!(list.windows(2).all(|w| w[0] < w[1]));
        }
    }

    #[test]
    fn top_holds_java_lang_and_kotlin_jvm_names() {
        for name in ["String", "Thread", "StringBuilder", "JvmStatic", "Volatile"] {
            assert!(has(TOP, name), "{name}");
        }
        assert!(!has(TOP, "NotAStdlibName"));
    }

    #[test]
    fn the_receiver_lists_keep_run_apart() {
        assert!(has(RECV_MEMBER, "run"));
        assert!(!has(RECV_BARE, "run"));
        assert!(has(RECV_BARE, "buildString"));
    }
}
