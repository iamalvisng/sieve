// Writes hooks/mascots.ts and assets/mascots-raw.ts from assets/mascots.json. Run: node scripts/gen-mascots.mjs
import { readFileSync, writeFileSync } from 'node:fs'
const dir = new URL('..', import.meta.url)
const j = JSON.parse(readFileSync(new URL('assets/mascots.json', dir), 'utf8'))
const mascots = Object.fromEntries(Object.entries(j.mascots).map(([k, m]) => [k, { name: m.name, frames: m.frames }]))
const out = `// Generated by scripts/gen-mascots.mjs from assets/mascots.json. Do not edit.
export const PALETTE: Record<string, string> = ${JSON.stringify(j.palette)}
export const MASCOTS: Record<string, { name: string; frames: string[][] }> = ${JSON.stringify(mascots, null, 1)}
export const DEFAULT_MASCOT = ${JSON.stringify(j.default)}
`
writeFileSync(new URL('hooks/mascots.ts', dir), out)
// The test cannot import a .json file, so a verbatim .ts copy of the JSON is the test's reference.
writeFileSync(new URL('assets/mascots-raw.ts', dir), `// Generated by scripts/gen-mascots.mjs: the JSON, verbatim. Do not edit.\nexport default ${JSON.stringify(j, null, 1)}\n`)
